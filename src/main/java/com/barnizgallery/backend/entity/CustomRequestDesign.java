package com.barnizgallery.backend.entity;

import java.time.Instant;

import org.hibernate.annotations.CreationTimestamp;

import com.barnizgallery.backend.converter.DesignStatusConverter;
import com.barnizgallery.backend.enums.DesignStatus;

import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

/**
 * A design image generated by AI for a custom request; at most one can be selected. Its status is kept as
 * text because the database does not define a fixed list. Maps the table {@code museo.custom_request_designs}.
 */
@Entity
@Table(name = "custom_request_designs")
public class CustomRequestDesign {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "design_id")
    private Long designId;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "custom_request_id", nullable = false)
    private CustomRequest customRequest;

    @Column(name = "provider", nullable = false)
    private String provider;

    @Column(name = "model", nullable = false)
    private String model;

    @Column(name = "prompt", nullable = false)
    private String prompt;

    @Convert(converter = DesignStatusConverter.class)
    @Column(name = "status", nullable = false, length = 30)
    private DesignStatus status;

    @Column(name = "image_url")
    private String imageUrl;

    @Column(name = "is_selected", nullable = false)
    private boolean selected = false;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    public Long getDesignId() {
        return designId;
    }

    public void setDesignId(Long designId) {
        this.designId = designId;
    }

    public CustomRequest getCustomRequest() {
        return customRequest;
    }

    public void setCustomRequest(CustomRequest customRequest) {
        this.customRequest = customRequest;
    }

    public String getProvider() {
        return provider;
    }

    public void setProvider(String provider) {
        this.provider = provider;
    }

    public String getModel() {
        return model;
    }

    public void setModel(String model) {
        this.model = model;
    }

    public String getPrompt() {
        return prompt;
    }

    public void setPrompt(String prompt) {
        this.prompt = prompt;
    }

    public DesignStatus getStatus() {
        return status;
    }

    public void setStatus(DesignStatus status) {
        this.status = status;
    }

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    public boolean isSelected() {
        return selected;
    }

    public void setSelected(boolean selected) {
        this.selected = selected;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }
}
