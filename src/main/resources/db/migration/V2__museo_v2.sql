CREATE TABLE orders (
  order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_code text NOT NULL UNIQUE,
  buyer_id bigint NOT NULL REFERENCES users(user_id), order_type varchar(20) NOT NULL CHECK(order_type IN ('compra','subasta','encargo')),
  status varchar(30) NOT NULL CHECK(status IN ('pendiente_pago','pagado','en_preparacion','enviado','entregado','cancelado','reembolsado')),
  subtotal numeric(14,2) NOT NULL CHECK(subtotal >= 0),
  shipping_cost numeric(14,2) NOT NULL DEFAULT 0 CHECK(shipping_cost >= 0),
  platform_fee numeric(14,2) NOT NULL DEFAULT 0 CHECK(platform_fee >= 0),
  total numeric(14,2) NOT NULL CHECK(total >= 0), currency varchar(3) NOT NULL DEFAULT 'USD',
  shipping_address jsonb NOT NULL, payment_due_at timestamptz, paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK(total = subtotal + shipping_cost)
);
CREATE TABLE order_items (
  order_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id bigint NOT NULL REFERENCES orders(order_id),
  store_id bigint NOT NULL REFERENCES stores(store_id), artwork_id bigint REFERENCES artworks(artwork_id),
  auction_id bigint, custom_offer_id bigint, quantity integer NOT NULL CHECK(quantity > 0),
  unit_price numeric(14,2) NOT NULL CHECK(unit_price >= 0), line_total numeric(14,2) NOT NULL CHECK(line_total >= 0),
  currency varchar(3) NOT NULL DEFAULT 'USD', artisan_gross_amount numeric(14,2) NOT NULL CHECK(artisan_gross_amount >= 0),
  platform_fee_amount numeric(14,2) NOT NULL CHECK(platform_fee_amount >= 0),
  artisan_net_amount numeric(14,2) NOT NULL CHECK(artisan_net_amount >= 0),
  fulfillment_status varchar(30) NOT NULL, carrier text, tracking_number text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((artwork_id IS NOT NULL)::integer + (auction_id IS NOT NULL)::integer + (custom_offer_id IS NOT NULL)::integer = 1),
  CHECK(line_total = quantity * unit_price),
  CHECK(artisan_gross_amount = platform_fee_amount + artisan_net_amount)
);
