  FOR EACH ROW EXECUTE FUNCTION refresh_order_platform_fee();

CREATE OR REPLACE FUNCTION refresh_order_totals() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_old_order bigint; v_new_order bigint;
BEGIN
