CREATE OR REPLACE FUNCTION prevent_currency_change_with_children() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_has_children boolean := false;
BEGIN
  IF NEW.currency IS NOT DISTINCT FROM OLD.currency THEN RETURN NEW; END IF;
  CASE TG_TABLE_NAME
    WHEN 'orders' THEN
      SELECT EXISTS(SELECT 1 FROM order_items WHERE order_id=OLD.order_id) OR
             EXISTS(SELECT 1 FROM payment_obligations WHERE order_id=OLD.order_id) INTO v_has_children;
    WHEN 'auctions' THEN
      IF OLD.currency IS NULL AND NEW.currency IS NOT NULL THEN
        SELECT EXISTS(SELECT 1 FROM bids WHERE auction_id=OLD.auction_id AND currency IS DISTINCT FROM NEW.currency) INTO v_has_children;
      ELSE
        SELECT EXISTS(SELECT 1 FROM bids WHERE auction_id=OLD.auction_id) INTO v_has_children;
      END IF;
    WHEN 'payment_obligations' THEN SELECT EXISTS(SELECT 1 FROM payments WHERE obligation_id=OLD.obligation_id) INTO v_has_children;
    WHEN 'payouts' THEN SELECT EXISTS(SELECT 1 FROM payout_items WHERE payout_id=OLD.payout_id) INTO v_has_children;
    WHEN 'order_items' THEN SELECT EXISTS(SELECT 1 FROM payout_items WHERE order_item_id=OLD.order_item_id) INTO v_has_children;
    WHEN 'custom_requests' THEN SELECT EXISTS(SELECT 1 FROM custom_offers WHERE custom_request_id=OLD.custom_request_id) INTO v_has_children;
    WHEN 'custom_offers' THEN SELECT EXISTS(SELECT 1 FROM order_items WHERE custom_offer_id=OLD.custom_offer_id) INTO v_has_children;
    WHEN 'artworks' THEN
      SELECT EXISTS(SELECT 1 FROM order_items WHERE artwork_id=OLD.artwork_id) OR
             EXISTS(SELECT 1 FROM auctions WHERE artwork_id=OLD.artwork_id) INTO v_has_children;
  END CASE;
  IF v_has_children THEN RAISE EXCEPTION 'La moneda no puede cambiar después de crear registros monetarios relacionados'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_currency_immutable BEFORE UPDATE OF currency ON orders FOR EACH ROW EXECUTE FUNCTION prevent_currency_change_with_children();
