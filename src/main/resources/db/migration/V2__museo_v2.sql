  avatar_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE, name_es text NOT NULL, name_en text NOT NULL,
  image_url text NOT NULL, sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
  is_active boolean NOT NULL DEFAULT true
);
CREATE TABLE users (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL, email varchar(255) NOT NULL,
  password_hash text, role varchar(20) NOT NULL CHECK (role IN ('administrador','artesano','cliente')),
  status varchar(20) NOT NULL DEFAULT 'pendiente' CHECK (status IN ('pendiente','activo','suspendido','eliminado')),
  avatar_id bigint REFERENCES avatars(avatar_id), phone text, country_code varchar(2), country_legacy text,
  preferred_language varchar(10) NOT NULL DEFAULT 'es' CHECK (preferred_language IN ('es','en')),
  email_verified_at timestamptz, last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_lower_uq ON users (lower(email));
