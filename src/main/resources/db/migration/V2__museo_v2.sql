CREATE TABLE artworks (
  artwork_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id bigint NOT NULL REFERENCES stores(store_id), title_es varchar(150) NOT NULL, title_en varchar(150) NOT NULL,
  history_es text, history_en text, technique varchar(150), slug text,
  dimensions_legacy text,
  shape_id bigint REFERENCES shapes(shape_id), style_id bigint REFERENCES styles(style_id),
  width_cm numeric(8,2) CHECK(width_cm IS NULL OR width_cm >= 0),
  height_cm numeric(8,2) CHECK(height_cm IS NULL OR height_cm >= 0),
  depth_cm numeric(8,2) CHECK(depth_cm IS NULL OR depth_cm >= 0), weight_g numeric(10,2) CHECK(weight_g IS NULL OR weight_g >= 0),
  sale_mode varchar(20) CHECK(sale_mode IS NULL OR sale_mode IN ('exhibicion','venta','subasta')),
  price numeric(14,2) CHECK(price IS NULL OR price >= 0), currency varchar(3),
  stock integer CHECK(stock IS NULL OR stock >= 0),
  status varchar(20) NOT NULL DEFAULT 'borrador' CHECK(status IN ('borrador','exhibida','subasta','reservada','vendida','archivada')),
  published_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), deleted_at timestamptz,
  UNIQUE(store_id, slug),
  CHECK(status = 'borrador' OR sale_mode <> 'venta' OR price IS NOT NULL)
