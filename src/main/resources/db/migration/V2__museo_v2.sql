CREATE OR REPLACE FUNCTION validate_order_item_auction_link() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_auction_id bigint; v_order_id bigint;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    v_auction_id := OLD.auction_id;
    IF v_auction_id IS NOT NULL THEN
      SELECT order_id INTO v_order_id FROM auctions WHERE auction_id=v_auction_id;
      IF v_order_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM order_items WHERE auction_id=v_auction_id AND order_id=v_order_id
      ) THEN RAISE EXCEPTION 'El pedido vinculado a la subasta debe conservar su línea de pedido'; END IF;
    END IF;
  END IF;
  IF TG_OP <> 'DELETE' THEN
    v_auction_id := NEW.auction_id;
    IF v_auction_id IS NOT NULL THEN
      SELECT order_id INTO v_order_id FROM auctions WHERE auction_id=v_auction_id;
      IF v_order_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM order_items WHERE auction_id=v_auction_id AND order_id=v_order_id
      ) THEN RAISE EXCEPTION 'El pedido vinculado a la subasta debe contener la línea de esa subasta'; END IF;
    END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER order_items_validate_auction_link
  AFTER INSERT OR UPDATE OR DELETE ON order_items DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION validate_order_item_auction_link();

-- Reservations are made explicitly by checkout inside its transaction. Adding an item
-- to cart never changes stock. Row locking serializes competing checkouts per artwork.
CREATE OR REPLACE FUNCTION reserve_order_item(p_order_item_id bigint, p_expires_at timestamptz)
RETURNS bigint LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_artwork bigint; v_qty integer; v_stock integer; v_reserved integer; v_id bigint;
        v_order bigint; v_order_type text; v_order_status text; v_existing_status text;
BEGIN
  IF p_expires_at <= now() THEN RAISE EXCEPTION 'La reserva debe vencer en el futuro'; END IF;
  SELECT COALESCE(i.artwork_id, a.artwork_id), i.quantity, i.order_id, o.order_type, o.status
  INTO v_artwork, v_qty, v_order, v_order_type, v_order_status
  FROM order_items i LEFT JOIN auctions u ON u.auction_id = i.auction_id
  LEFT JOIN artworks a ON a.artwork_id = u.artwork_id
  JOIN orders o ON o.order_id=i.order_id
  WHERE i.order_item_id = p_order_item_id FOR UPDATE OF i, o;
  IF v_artwork IS NULL THEN RAISE EXCEPTION 'La línea no representa una obra inventariable'; END IF;
  IF v_order_type NOT IN ('compra','subasta') THEN
    RAISE EXCEPTION 'Los pedidos por encargo no reservan inventario de obras';
  END IF;
  IF v_order_status <> 'pendiente_pago' THEN RAISE EXCEPTION 'El pedido no admite nuevas reservas'; END IF;
  SELECT reservation_id, status INTO v_id, v_existing_status
  FROM inventory_reservations WHERE order_item_id=p_order_item_id
  ORDER BY reservation_id DESC LIMIT 1 FOR UPDATE;
  IF v_existing_status='consumida' THEN RAISE EXCEPTION 'La reserva de esta línea ya fue consumida'; END IF;
  IF v_existing_status='activa' AND EXISTS (
    SELECT 1 FROM inventory_reservations WHERE reservation_id=v_id AND expires_at>now()
  ) THEN RETURN v_id; END IF;
  -- Expire only elapsed reservations with no pending gateway attempt. A pending
  -- attempt continues to hold stock until its result is reconciled.
  PERFORM expire_inventory_reservations(now());
  IF EXISTS (SELECT 1 FROM inventory_reservations WHERE reservation_id=v_id AND status='activa') THEN
    RAISE EXCEPTION 'La reserva vencida sigue protegida por un intento de pago pendiente';
  END IF;
  SELECT stock INTO v_stock FROM artworks WHERE artwork_id = v_artwork FOR UPDATE;
  IF v_stock IS NULL THEN RAISE EXCEPTION 'El inventario de la obra no está configurado'; END IF;
  SELECT COALESCE(sum(quantity),0)::integer INTO v_reserved FROM inventory_reservations
    WHERE artwork_id=v_artwork AND status='activa';
  IF v_reserved + v_qty > v_stock THEN RAISE EXCEPTION 'Existencias insuficientes'; END IF;
  INSERT INTO inventory_reservations(order_item_id,artwork_id,quantity,status,expires_at)
    VALUES(p_order_item_id,v_artwork,v_qty,'activa',p_expires_at) RETURNING reservation_id INTO v_id;
  RETURN v_id;
END $$;

CREATE OR REPLACE FUNCTION settle_reservations_for_order(p_order_id bigint) RETURNS void LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE r record; v_order_type text; v_order_status text; v_stock_lines integer;
        v_all_consumed boolean; v_any_consumed boolean;
BEGIN
  SELECT order_type,status INTO v_order_type,v_order_status FROM orders
  WHERE order_id=p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Pedido inexistente'; END IF;
  IF v_order_type='encargo' THEN RETURN; END IF;
  IF v_order_type NOT IN ('compra','subasta') THEN RAISE EXCEPTION 'Tipo de pedido no inventariable'; END IF;

  SELECT count(*) INTO v_stock_lines FROM order_items oi WHERE oi.order_id=p_order_id
    AND (oi.artwork_id IS NOT NULL OR oi.auction_id IS NOT NULL);
  IF v_stock_lines=0 THEN RAISE EXCEPTION 'El pedido requiere al menos una línea de obra'; END IF;
  IF EXISTS (
    SELECT 1 FROM order_items oi LEFT JOIN auctions u ON u.auction_id=oi.auction_id
    WHERE oi.order_id=p_order_id AND (oi.artwork_id IS NOT NULL OR oi.auction_id IS NOT NULL)
      AND ((SELECT count(*) FROM inventory_reservations ir WHERE ir.order_item_id=oi.order_item_id
            AND ir.status IN ('activa','consumida')) <> 1
        OR NOT EXISTS (SELECT 1 FROM inventory_reservations ir WHERE ir.order_item_id=oi.order_item_id
          AND ir.status IN ('activa','consumida')
          AND ir.artwork_id=COALESCE(oi.artwork_id,u.artwork_id) AND ir.quantity=oi.quantity))
  ) THEN RAISE EXCEPTION 'Cada línea de obra debe tener exactamente una reserva activa o consumida'; END IF;
  SELECT bool_and(ir.status='consumida'), bool_or(ir.status='consumida')
  INTO v_all_consumed,v_any_consumed
  FROM order_items oi JOIN inventory_reservations ir ON ir.order_item_id=oi.order_item_id
  WHERE oi.order_id=p_order_id AND (oi.artwork_id IS NOT NULL OR oi.auction_id IS NOT NULL);
  IF v_all_consumed THEN RETURN; END IF;
  IF v_any_consumed THEN RAISE EXCEPTION 'Estado parcial de consumo de reservas; no se puede liquidar el pedido'; END IF;
  IF v_order_status IN ('cancelado','reembolsado') THEN RAISE EXCEPTION 'No se consume inventario para un pedido terminal'; END IF;
  IF EXISTS (
    SELECT 1 FROM order_items oi WHERE oi.order_id=p_order_id
      AND (oi.artwork_id IS NOT NULL OR oi.auction_id IS NOT NULL)
      AND NOT EXISTS (SELECT 1 FROM inventory_reservations ir WHERE ir.order_item_id=oi.order_item_id
        AND ir.status='activa' AND ir.expires_at>now())
  ) THEN RAISE EXCEPTION 'La reserva expiró o no existe al aprobar el pago'; END IF;
  FOR r IN SELECT ir.reservation_id, ir.artwork_id, ir.quantity FROM inventory_reservations ir
    JOIN order_items oi ON oi.order_item_id=ir.order_item_id
    WHERE oi.order_id=p_order_id AND ir.status='activa' AND ir.expires_at>now()
    ORDER BY ir.artwork_id,ir.reservation_id FOR UPDATE OF ir LOOP
    UPDATE artworks SET stock=stock-r.quantity, updated_at=now()
      WHERE artwork_id=r.artwork_id AND stock >= r.quantity;
    IF NOT FOUND THEN RAISE EXCEPTION 'Inventario insuficiente al aprobar pago'; END IF;
    UPDATE inventory_reservations SET status='consumida', updated_at=now()
      WHERE reservation_id=r.reservation_id AND status='activa' AND expires_at>now();
    IF NOT FOUND THEN RAISE EXCEPTION 'La reserva cambió antes de consumirse'; END IF;
  END LOOP;
END $$;
CREATE OR REPLACE FUNCTION release_reservations_for_order(p_order_id bigint, p_new_status text DEFAULT 'liberada') RETURNS void LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_order_type text; v_order_status text; v_target text := p_new_status;
BEGIN
  IF p_new_status NOT IN ('liberada','expirada') THEN RAISE EXCEPTION 'Estado de liberación inválido'; END IF;
  SELECT order_type,status INTO v_order_type,v_order_status FROM orders WHERE order_id=p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order_type='encargo' THEN RETURN; END IF;
  -- A pending gateway attempt on any stage blocks release. This is deliberately
  -- order-wide so one rejected stage cannot free stock needed by another stage.
  IF EXISTS (
    SELECT 1 FROM payment_obligations po JOIN payments pay USING(obligation_id)
    WHERE po.order_id=p_order_id AND pay.status='pendiente'
  ) THEN RETURN; END IF;
  IF v_order_status='pendiente_pago' AND EXISTS (
    SELECT 1 FROM payment_obligations po WHERE po.order_id=p_order_id AND po.status='pagada'
  ) THEN RETURN; END IF;
  IF p_new_status='liberada' AND v_order_status NOT IN ('cancelado','reembolsado') THEN
    -- A rejected attempt is retryable while any reservation remains in its window.
    IF EXISTS (SELECT 1 FROM inventory_reservations ir JOIN order_items oi USING(order_item_id)
      WHERE oi.order_id=p_order_id AND ir.status='activa' AND ir.expires_at>now()) THEN RETURN; END IF;
    v_target := 'expirada';
  END IF;
  IF v_target='expirada' AND EXISTS (
    SELECT 1 FROM inventory_reservations ir JOIN order_items oi USING(order_item_id)
    WHERE oi.order_id=p_order_id AND ir.status='activa' AND ir.expires_at>now()
  ) THEN RETURN; END IF;
  UPDATE inventory_reservations ir SET status=v_target, updated_at=now()
  FROM order_items oi WHERE oi.order_item_id=ir.order_item_id AND oi.order_id=p_order_id
    AND ir.status='activa'
    AND ((v_target='expirada' AND ir.expires_at<=now()) OR v_target='liberada');
END $$;

CREATE OR REPLACE FUNCTION expire_inventory_reservations(p_as_of timestamptz DEFAULT now())
RETURNS integer LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_count integer;
BEGIN
  UPDATE inventory_reservations ir
  SET status='expirada', updated_at=now()
  FROM order_items oi, orders o
  WHERE oi.order_item_id=ir.order_item_id AND o.order_id=oi.order_id
    AND ir.status='activa' AND ir.expires_at <= p_as_of
    AND o.order_type IN ('compra','subasta')
    AND o.status IN ('pendiente_pago','cancelado','reembolsado')
    AND NOT EXISTS (SELECT 1 FROM payment_obligations po JOIN payments pay USING(obligation_id)
      WHERE po.order_id=o.order_id AND pay.status='pendiente')
    AND (o.status<>'pendiente_pago' OR NOT EXISTS (
      SELECT 1 FROM payment_obligations po WHERE po.order_id=o.order_id AND po.status='pagada'
    ));
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END $$;

CREATE OR REPLACE FUNCTION handle_payment_reservation() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_order bigint; v_order_type text; v_order_status text; v_old_status text;
BEGIN
  IF TG_OP='INSERT' THEN v_old_status := NULL; ELSE v_old_status := OLD.status; END IF;
  IF NEW.status IS DISTINCT FROM v_old_status THEN
    SELECT po.order_id,o.order_type,o.status INTO v_order,v_order_type,v_order_status
    FROM payment_obligations po JOIN orders o USING(order_id)
    WHERE po.obligation_id=NEW.obligation_id FOR UPDATE OF o;
    IF NEW.status='aprobado' THEN
      IF v_order_status IN ('cancelado','reembolsado') THEN
        RAISE EXCEPTION 'No se puede aprobar un pago de un pedido terminal';
      END IF;
      UPDATE payment_obligations SET status='pagada', updated_at=now() WHERE obligation_id=NEW.obligation_id;
      IF NOT EXISTS (SELECT 1 FROM payment_obligations WHERE order_id=v_order AND status<>'pagada') THEN
        -- A custom order has no stock reservation. Purchase and auction stock is
        -- consumed only after every obligation for the order is paid.
        IF v_order_type IN ('compra','subasta') THEN
          PERFORM settle_reservations_for_order(v_order);
        END IF;
        UPDATE orders SET status='pagado', paid_at=COALESCE(paid_at,now()), updated_at=now()
        WHERE order_id=v_order AND status<>'pagado';
      END IF;
    ELSIF NEW.status IN ('rechazado','expirado') THEN
      PERFORM release_reservations_for_order(v_order,CASE WHEN NEW.status='expirado' THEN 'expirada' ELSE 'liberada' END);
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER payments_reservation_state AFTER INSERT OR UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION handle_payment_reservation();

CREATE OR REPLACE FUNCTION record_order_status_change() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_actor bigint;
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    v_actor := nullif(current_setting('app.user_id', true),'')::bigint;
    INSERT INTO order_status_history(order_id,old_status,new_status,changed_by,changed_at)
      VALUES(NEW.order_id,OLD.status,NEW.status,v_actor,now());
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_record_status_history AFTER UPDATE OF status ON orders
  FOR EACH ROW EXECUTE FUNCTION record_order_status_change();

-- Audit actor is read from transaction-local app.user_id; secrets/password_hash are excluded.
CREATE OR REPLACE FUNCTION audit_row_change() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_actor bigint; v_old jsonb; v_new jsonb; v_id text;
BEGIN
  v_actor := nullif(current_setting('app.user_id', true),'')::bigint;
  IF TG_OP <> 'INSERT' THEN v_old := to_jsonb(OLD) - 'password_hash'; END IF;
  IF TG_OP <> 'DELETE' THEN v_new := to_jsonb(NEW) - 'password_hash'; END IF;
  v_id := COALESCE(v_new->>'user_id',v_new->>'master_id',v_new->>'store_id',v_new->>'artwork_id',v_new->>'auction_id',v_new->>'order_id',v_new->>'payment_id',v_new->>'custom_offer_id',v_new->>'verification_id',v_new->>'setting_key',v_old->>'user_id',v_old->>'master_id',v_old->>'store_id',v_old->>'artwork_id',v_old->>'auction_id',v_old->>'order_id',v_old->>'payment_id',v_old->>'custom_offer_id',v_old->>'verification_id',v_old->>'setting_key');
  INSERT INTO audit_log(table_name,record_id,action,changed_by,old_data,new_data)
    VALUES(TG_TABLE_NAME,v_id,TG_OP,v_actor,v_old,v_new);
  RETURN NULL;
END $$;
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['users','masters','stores','artworks','auctions','orders','payments','custom_offers','app_settings','master_verifications'] LOOP
    EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION audit_row_change()',t || '_audit',t);
  END LOOP;
END $$;

