    UPDATE orders SET subtotal=COALESCE((SELECT sum(line_total) FROM order_items WHERE order_id=v_new_order),0),
      total=COALESCE((SELECT sum(line_total) FROM order_items WHERE order_id=v_new_order),0)+shipping_cost
      WHERE order_id=v_new_order;
  ELSIF v_new_order IS NOT NULL THEN
    UPDATE orders SET subtotal=COALESCE((SELECT sum(line_total) FROM order_items WHERE order_id=v_new_order),0),
      total=COALESCE((SELECT sum(line_total) FROM order_items WHERE order_id=v_new_order),0)+shipping_cost
