CREATE OR REPLACE FUNCTION validate_accepted_offer_state() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_request bigint; v_offer bigint; v_status text;
BEGIN
  IF TG_TABLE_NAME='custom_requests' THEN
    v_request := COALESCE(NEW.custom_request_id, OLD.custom_request_id);
    SELECT accepted_offer_id INTO v_offer FROM custom_requests WHERE custom_request_id=v_request;
    IF v_offer IS NOT NULL THEN
      SELECT status INTO v_status FROM custom_offers WHERE custom_offer_id=v_offer AND custom_request_id=v_request;
      IF v_status IS DISTINCT FROM 'aceptada' THEN RAISE EXCEPTION 'La oferta vinculada debe estar aceptada'; END IF;
    END IF;
  ELSE
    v_request := COALESCE(NEW.custom_request_id, OLD.custom_request_id);
    v_offer := COALESCE(NEW.custom_offer_id, OLD.custom_offer_id);
    IF NEW.status='aceptada' AND NOT EXISTS (
      SELECT 1 FROM custom_requests WHERE custom_request_id=v_request AND accepted_offer_id=v_offer
    ) THEN RAISE EXCEPTION 'La oferta aceptada debe ser la oferta señalada por el encargo'; END IF;
    IF EXISTS (SELECT 1 FROM custom_requests WHERE custom_request_id=v_request AND accepted_offer_id=v_offer)
       AND (SELECT status FROM custom_offers WHERE custom_offer_id=v_offer) IS DISTINCT FROM 'aceptada' THEN
      RAISE EXCEPTION 'No se puede retirar el estado aceptado de la oferta referenciada';
    END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER request_accepted_offer_state AFTER INSERT OR UPDATE ON custom_requests
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_accepted_offer_state();
CREATE CONSTRAINT TRIGGER offer_accepted_state AFTER INSERT OR UPDATE ON custom_offers
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_accepted_offer_state();

CREATE OR REPLACE FUNCTION validate_message_participant() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_customer bigint; v_master_user bigint;
BEGIN
  SELECT c.customer_id, m.user_id INTO v_customer, v_master_user
  FROM conversations c JOIN masters m ON m.master_id = c.master_id
  WHERE c.conversation_id = NEW.conversation_id FOR SHARE OF c, m;
  IF NEW.sender_id IS DISTINCT FROM v_customer AND NEW.sender_id IS DISTINCT FROM v_master_user THEN
    RAISE EXCEPTION 'El remitente no participa en esta conversación';
  END IF;
  IF v_master_user IS NULL AND NEW.sender_id IS DISTINCT FROM v_customer THEN
    RAISE EXCEPTION 'El maestro todavía no tiene usuario verificado';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER messages_sender_must_participate BEFORE INSERT OR UPDATE OF conversation_id, sender_id ON messages
  FOR EACH ROW EXECUTE FUNCTION validate_message_participant();

CREATE OR REPLACE FUNCTION validate_conversation_context() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
BEGIN
  IF NEW.artwork_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM artworks a JOIN stores s USING(store_id)
    WHERE a.artwork_id=NEW.artwork_id AND s.master_id=NEW.master_id
  ) THEN RAISE EXCEPTION 'La obra debe pertenecer al maestro de la conversación'; END IF;
  IF NEW.custom_request_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM custom_requests cr
    WHERE cr.custom_request_id=NEW.custom_request_id AND cr.buyer_id=NEW.customer_id
      AND (cr.target_master_id IS NULL OR cr.target_master_id=NEW.master_id)
  ) THEN RAISE EXCEPTION 'El encargo debe corresponder al cliente y maestro de la conversación'; END IF;
  IF NEW.order_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM orders o JOIN order_items oi USING(order_id) JOIN stores s USING(store_id)
    WHERE o.order_id=NEW.order_id AND o.buyer_id=NEW.customer_id AND s.master_id=NEW.master_id
  ) THEN RAISE EXCEPTION 'El pedido debe incluir una línea de la tienda del maestro y pertenecer al cliente'; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER conversations_validate_context BEFORE INSERT OR UPDATE OF customer_id,master_id,artwork_id,custom_request_id,order_id ON conversations
  FOR EACH ROW EXECUTE FUNCTION validate_conversation_context();

CREATE OR REPLACE FUNCTION validate_order_item_source() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_store bigint; v_master bigint; v_order_type text; v_auction_order bigint; v_source_currency varchar(3);
BEGIN
  SELECT order_type INTO v_order_type FROM orders WHERE order_id=NEW.order_id;
  IF NEW.artwork_id IS NOT NULL THEN
    SELECT store_id, currency INTO v_store, v_source_currency FROM artworks WHERE artwork_id = NEW.artwork_id FOR SHARE;
    IF v_order_type <> 'compra' THEN RAISE EXCEPTION 'Una compra directa requiere pedido tipo compra'; END IF;
  ELSIF NEW.auction_id IS NOT NULL THEN
    SELECT a.store_id, u.order_id, u.currency INTO v_store, v_auction_order, v_source_currency FROM auctions u JOIN artworks a ON a.artwork_id = u.artwork_id
      WHERE u.auction_id = NEW.auction_id FOR SHARE OF u, a;
    IF v_order_type <> 'subasta' THEN RAISE EXCEPTION 'Una línea de subasta requiere pedido tipo subasta'; END IF;
    IF v_auction_order IS NOT NULL AND v_auction_order IS DISTINCT FROM NEW.order_id THEN
      RAISE EXCEPTION 'La línea debe pertenecer al pedido vinculado a la subasta';
    END IF;
  ELSE
    SELECT store_id, master_id, currency INTO v_store, v_master, v_source_currency FROM custom_offers
      WHERE custom_offer_id = NEW.custom_offer_id AND status = 'aceptada' FOR SHARE;
    IF v_store IS NULL THEN RAISE EXCEPTION 'La oferta debe existir y estar aceptada'; END IF;
    IF v_order_type <> 'encargo' THEN RAISE EXCEPTION 'Una oferta requiere pedido tipo encargo'; END IF;
  END IF;
  IF v_store IS DISTINCT FROM NEW.store_id THEN RAISE EXCEPTION 'La tienda de la línea no coincide con su origen'; END IF;
  IF v_source_currency IS NULL THEN RAISE EXCEPTION 'La moneda del origen debe configurarse antes de crear una línea de pedido';
  ELSIF v_source_currency IS DISTINCT FROM NEW.currency THEN
    RAISE EXCEPTION 'La moneda de la línea debe coincidir con la de su origen';
  END IF;
  IF NEW.custom_offer_id IS NOT NULL THEN
    SELECT master_id INTO v_master FROM stores WHERE store_id = NEW.store_id;
    IF NOT EXISTS (SELECT 1 FROM custom_offers WHERE custom_offer_id = NEW.custom_offer_id AND master_id = v_master) THEN
      RAISE EXCEPTION 'Oferta y tienda no corresponden al mismo maestro';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER order_items_validate_source BEFORE INSERT OR UPDATE OF order_id, store_id, artwork_id, auction_id, custom_offer_id, currency ON order_items
  FOR EACH ROW EXECUTE FUNCTION validate_order_item_source();

