CREATE OR REPLACE FUNCTION refresh_order_platform_fee() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_old_order bigint; v_new_order bigint;
BEGIN
  IF TG_OP <> 'INSERT' THEN v_old_order := OLD.order_id; END IF;
  IF TG_OP <> 'DELETE' THEN v_new_order := NEW.order_id; END IF;
  IF v_old_order IS NOT NULL THEN
    UPDATE orders SET platform_fee=COALESCE((SELECT sum(platform_fee_amount) FROM order_items WHERE order_id=v_old_order),0)
      WHERE order_id=v_old_order;
  END IF;
  IF v_new_order IS NOT NULL AND v_new_order IS DISTINCT FROM v_old_order THEN
    UPDATE orders SET platform_fee=COALESCE((SELECT sum(platform_fee_amount) FROM order_items WHERE order_id=v_new_order),0)
      WHERE order_id=v_new_order;
  ELSIF v_new_order IS NOT NULL THEN
    UPDATE orders SET platform_fee=COALESCE((SELECT sum(platform_fee_amount) FROM order_items WHERE order_id=v_new_order),0)
      WHERE order_id=v_new_order;
  END IF;
  RETURN NULL;
END $$;
