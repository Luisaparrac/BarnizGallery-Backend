CREATE OR REPLACE FUNCTION enforce_store_publication_approval() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_status text;
BEGIN
  IF NEW.status = 'publicada' AND (TG_OP = 'INSERT' OR OLD.status IS DISTINCT FROM NEW.status OR OLD.master_id IS DISTINCT FROM NEW.master_id) THEN
    SELECT verification_status INTO v_status FROM masters WHERE master_id = NEW.master_id FOR UPDATE;
    IF v_status IS DISTINCT FROM 'aprobado' THEN
      RAISE EXCEPTION 'La tienda solo puede publicarse cuando el maestro está aprobado';
    END IF;
  END IF;
  RETURN NEW;
END $$;
