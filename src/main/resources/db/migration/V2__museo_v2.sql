CREATE OR REPLACE FUNCTION validate_encargo_obligations() RETURNS trigger LANGUAGE plpgsql SET search_path = museo, pg_catalog AS $$
DECLARE v_order bigint; v_type text; v_stages bigint; v_other bigint; v_total numeric(14,2); v_single_amount numeric(14,2);
BEGIN
  v_order := COALESCE(NEW.order_id, OLD.order_id);
  SELECT order_type,total INTO v_type,v_total FROM orders WHERE order_id = v_order;
  IF v_type IS NULL THEN RETURN NULL; END IF;
  SELECT count(*) FILTER (WHERE stage IN ('anticipo','saldo')), count(*) FILTER (WHERE stage = 'pago_unico')
    INTO v_stages, v_other FROM payment_obligations WHERE order_id = v_order;
  IF v_type = 'encargo' AND (v_stages <> 2 OR v_other <> 0) THEN
    RAISE EXCEPTION 'Un pedido de encargo requiere exactamente anticipo y saldo';
  ELSIF v_type <> 'encargo' AND (v_other <> 1 OR v_stages <> 0) THEN
    RAISE EXCEPTION 'Un pedido ordinario o de subasta requiere una obligación pago_unico';
  ELSIF v_type <> 'encargo' THEN
    SELECT amount INTO v_single_amount FROM payment_obligations WHERE order_id=v_order AND stage='pago_unico';
    IF v_single_amount IS DISTINCT FROM v_total THEN RAISE EXCEPTION 'La obligación única debe cubrir el total del pedido'; END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER orders_check_obligations AFTER INSERT OR UPDATE ON orders
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_encargo_obligations();
