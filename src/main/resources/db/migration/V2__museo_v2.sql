-- Flyway V2: run against a PostgreSQL 18 database baselined at V1.
-- Archives the original public tables, then imports their data into museo.
-- Historical timestamps remain timestamp without time zone; no source timezone is assumed.
SET TIME ZONE 'UTC';
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['masters','rooms','artworks','photos','three_d_models','visitors','taste_profiles','interactions','recommendations','auctions','bids','contact_messages'] LOOP
    IF to_regclass('public.' || quote_ident(t)) IS NULL THEN
      RAISE EXCEPTION 'Required MUSEO v1 table public.% is missing', t;
    END IF;
    IF to_regclass('public.' || quote_ident('museo_v1_' || t)) IS NOT NULL THEN
      RAISE EXCEPTION 'Archive table public.museo_v1_% already exists', t;
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM public.bids WHERE length(currency) > 3) THEN
    RAISE EXCEPTION 'A historical bid currency exceeds the v2 ISO currency column; migration stopped without truncation';
  END IF;
  FOREACH t IN ARRAY ARRAY['masters','rooms','artworks','photos','three_d_models','visitors','taste_profiles','interactions','recommendations','auctions','bids','contact_messages'] LOOP
    EXECUTE format('ALTER TABLE public.%I RENAME TO %I', t, 'museo_v1_' || t);
  END LOOP;
END $$;

