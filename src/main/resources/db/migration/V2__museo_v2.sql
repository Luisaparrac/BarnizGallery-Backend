-- Align all identity sequences with explicit legacy IDs and seeded catalog IDs.
DO $$
DECLARE r record; v_seq text; v_max bigint;
BEGIN
  FOR r IN
    SELECT table_schema,table_name,column_name FROM information_schema.columns
    WHERE table_schema='museo' AND is_identity='YES'
  LOOP
    v_seq := pg_get_serial_sequence(format('%I.%I',r.table_schema,r.table_name),r.column_name);
    EXECUTE format('SELECT max(%I) FROM %I.%I',r.column_name,r.table_schema,r.table_name) INTO v_max;
    IF v_seq IS NOT NULL THEN PERFORM setval(v_seq::regclass,COALESCE(v_max,1),v_max IS NOT NULL); END IF;
  END LOOP;
END $$;

